public class Tugas1 {

    static void main(String[] args) {

        //Deklarasi Variabel
        int a = 10;
        int b = 5;

        //Operasi Aritmatika
        int sum = a + b;
        System.out.println("Hasil Penjumlahan  " + a + " + " + b + " : " + sum);

        int difference = a - b;
        System.out.println("Hasil Pengurangan " + a + " - " + b + " : " + difference);

        int product = a * b;
        System.out.println("Hasil Perkalian " + a + " * " + b + " : " + product);

        int quotient = a / b;
        System.out.println("Hasil Pembagian " + a + " / " + b + " : " + quotient);

        int remainder = a % b;
        System.out.println("Hasil Modulus " + a + " % " + b + " : " + remainder);
    }
}
